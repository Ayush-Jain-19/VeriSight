"""Directional checks using published weights, attributed samples and real codecs."""
import argparse
from pathlib import Path
import subprocess
import tempfile
import os
import sys

from src.inference.pipeline import InferencePipeline, FACE
from src.inference.speech import ASR, ONNX_AUDIO, onnx_audio_files

# Opening of Jane Austen's Pride and Prejudice, public domain.
HUMAN = ("It is a truth universally acknowledged, that a single man in possession of a good "
         "fortune, must be in want of a wife. However little known the feelings or views of "
         "such a man may be on his first entering a neighbourhood, this truth is so well fixed "
         "in the minds of the surrounding families, that he is considered as the rightful "
         "property of some one or other of their daughters.")
# Generated by the coding assistant specifically for this smoke check.
GENERATED = ("Urban gardens can offer a wide range of benefits for local communities. By "
             "transforming unused spaces into productive green areas, residents can foster "
             "social connections and promote environmental sustainability. Furthermore, these "
             "initiatives provide valuable opportunities for education, collaboration, and "
             "personal growth. In conclusion, the development of community gardens can play "
             "a significant role in creating healthier and more resilient neighborhoods.")


# Human passages predate widespread generative writing tools. Keep domains visible.
# NASA, "New Crew Launches to Space Station to Continue Scientific Research", 2014.
# https://www.nasa.gov/news-release/new-crew-launches-to-space-station-to-continue-scientific-research-4/
NEWS = ("The International Space Station is a convergence of science, technology and human "
        "innovation that demonstrates new technologies and makes research breakthroughs not possible on Earth.")
# Don Pettit, "A Slice of Time Pie", Air & Space Magazine, June 22, 2012.
# https://www.smithsonianmag.com/air-space-magazine/a-slice-of-time-pie-134485181/
CASUAL = ("I might make a list of tools so that when I float to the tool box, "
          "I can gather everything I need in one trip.")
# Generated for this comparison, before either checkpoint was run.
AI_NEWS = ("The station crew completed a maintenance check on Tuesday, clearing the way "
           "for a new series of experiments on plant growth in orbit.")
AI_CASUAL = ("I left my mug on the windowsill again. If you spot it before I get home, "
             "could you bring it in? The rain looks close.")
TEXT_PAIRS = (
    ("modern news", NEWS, "generated news", AI_NEWS),
    ("casual writing", CASUAL, "generated casual", AI_CASUAL),
    ("classic Austen", HUMAN, "generated essay", GENERATED),
)


def check_text(pipe, pairs, failures):
    correct = 0
    for domain, human, generated_name, generated in pairs:
        results = []
        for name, passage, expected in [(domain, human, "REAL"), (generated_name, generated, "FAKE")]:
            result = pipe.predict_text(passage)
            results.append(result["text"])
            correct += result["prediction"] == expected
            print(f"text {name}: score={result['text']['score']} verdict={result['prediction']} expected={expected}", flush=True)
        check_pair(domain, *results, failures, echo=False)
    print(f"text decisions correct: {correct}/{2*len(pairs)} (abstentions count as unresolved)", flush=True)


def download(config):
    from huggingface_hub import snapshot_download
    for name, files in [(config.inference.text_model, ["*.json","vocab.json","merges.txt","model.safetensors"]),
                        (config.inference.audio_model, ["*.json","model.safetensors"]),
                        (ASR, ["*.json","vocabulary.txt","model.bin"]),
                        (FACE, ["labels_v2.json","deepfakeguard_v2.onnx"]),
                        ("Organika/sdxl-detector", ["*.json","model.safetensors","pytorch_model.bin"])]:
        if name == ONNX_AUDIO:
            onnx_audio_files()
        else:
            snapshot_download(name, allow_patterns=files, max_workers=1)


def check_pair(name, human, generated, failures, echo=True):
    low, high = human["score"], generated["score"]
    if echo:
        print(f"{name}: human={low}, generated={high}", flush=True)
    if low is None or high is None:
        failures.append(f"{name}: missing real inference: {human.get('reason')} / {generated.get('reason')}")
    elif high <= low or max(abs(low-.5), abs(high-.5)) < .01:
        failures.append(f"{name}: " + ("generated score did not exceed human score" if high <= low else "both scores within 0.01 of 0.5"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--download", action="store_true")
    parser.add_argument("--real-audio", type=Path)
    parser.add_argument("--synthetic-audio", type=Path, default=Path("demo_samples/test_speech_synthesis.wav"))
    parser.add_argument("--real-text", type=Path)
    parser.add_argument("--generated-text", type=Path)
    parser.add_argument("--text-only", action="store_true", help="Score passages only")
    parser.add_argument("--text-model", help="Override the configured pretrained text checkpoint")
    args = parser.parse_args()
    from src.config import load_config
    config = load_config()
    if args.text_model:
        config.inference.text_model = args.text_model
    if args.download:
        download(config)
        return
    import torch
    torch.set_num_threads(2)
    pipe = InferencePipeline(config)
    failures = []
    pairs = TEXT_PAIRS
    if args.real_text or args.generated_text:
        human = args.real_text.read_text(encoding="utf-8") if args.real_text else HUMAN
        generated = args.generated_text.read_text(encoding="utf-8") if args.generated_text else GENERATED
        pairs = [("custom human", human, "custom generated", generated)]
    check_text(pipe, pairs, failures)
    if not args.text_only:
        check_audio(pipe, args, failures)
    report_peak()
    if failures:
        raise SystemExit("\n".join(failures))
    print("PASS: directional text checks" if args.text_only else "PASS: directional and codec smoke checks")


def check_audio(pipe, args, failures):
    with tempfile.TemporaryDirectory() as directory:
        real = args.real_audio
        if real is None:
            import urllib.request
            real = Path(directory)/"5703-47212-0000.ogg"
            urllib.request.urlretrieve("https://librosa.org/data/audio/5703-47212-0000.ogg", real)
        positive = pipe.predict_audio(args.synthetic_audio)["audio"]
        check_pair("speech", pipe.predict_audio(real)["audio"], positive, failures)
        for suffix in ["m4a","aac"]:
            encoded = Path(directory)/f"speech.{suffix}"
            subprocess.run(["ffmpeg","-nostdin","-v","error","-i",str(args.synthetic_audio),
                            "-c:a","aac",str(encoded)],check=True)
            branch = pipe.predict_audio(encoded)["audio"]
            print(f"{suffix}: duration={branch.get('duration_seconds')}, score={branch['score']}", flush=True)
            if branch["score"] is None or branch.get("duration_seconds",0) <= .5:
                failures.append(f"{suffix}: {branch.get('reason')}")


def report_peak():
    if os.name == "nt":
        output = subprocess.check_output(["powershell", "-NoProfile", "-Command",
                    f"(Get-Process -Id {os.getpid()}).PeakWorkingSet64"])
        print(f"Process peak working set: {int(output.strip())/1e6:.1f} MB")
    elif sys.platform.startswith("linux"):
        import resource
        print(f"Peak resident memory: {resource.getrusage(resource.RUSAGE_SELF).ru_maxrss*1024/1e6:.1f} MB")


if __name__ == "__main__":
    main()
